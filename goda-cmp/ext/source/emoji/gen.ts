import {
  EMOJIS,
  EMOJIS_ALIAS,
} from "https://raw.githubusercontent.com/99x/emojideno/master/src/constants.ts";

const escape = (s: string) =>
  [...s].map((c) =>
    `\\U${c.codePointAt(0)!.toString(16).toUpperCase().padStart(8, "0")}`
  ).join("");

const rows = [...Object.entries(EMOJIS), ...Object.entries(EMOJIS_ALIAS)]
  .map(([name, emoji]) =>
    `\t{${JSON.stringify(name)}, "${escape(emoji as string)}"},`
  );

Deno.writeTextFileSync(
  new URL("table.go", import.meta.url),
  `// Code generated by gen.ts. DO NOT EDIT.

package emoji

var table = []Metadata{
${rows.join("\n")}
}
`,
);
